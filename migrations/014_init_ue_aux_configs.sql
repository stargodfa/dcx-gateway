-- Supplemental UE configuration domains for dcx-gateway.
-- Names and columns remain compatible with the source Gateway for data transfer.
CREATE TABLE IF NOT EXISTS model_anchors (
  anchor_id VARCHAR(64) NOT NULL PRIMARY KEY,
  instance_id VARCHAR(128) NOT NULL,
  revision INT NOT NULL DEFAULT 0,
  payload JSON NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS sensor_devices (
  device_id VARCHAR(128) NOT NULL PRIMARY KEY,
  payload JSON NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS cluster_agents_catalog (
  node_id VARCHAR(128) NOT NULL PRIMARY KEY,
  payload JSON NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS cluster_agent_registry (
  node_id VARCHAR(128) NOT NULL PRIMARY KEY,
  enabled TINYINT NOT NULL DEFAULT 0,
  payload JSON NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
